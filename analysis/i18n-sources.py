#!/usr/bin/env python3
"""Where GL.iNet's interface translations come from: for every release, each
/www/i18n file of the official image that GL.iNet's public language
repository (gl-inet/router-sdk-languages) has byte for byte, with the commit
that introduced it and its path there.

    sudo i18n-sources.py <language repo clone> <roots dir> <out dir> [release ...]

Writes <out dir>/<release>.md (a table read by .github/scripts/gen-closed-feed.py
--i18n=...): image file, commit, path in the repository, SHA256. Files the
repository doesn't have are listed below the table and stay as copied from
the image. Run on a machine with the unpacked images; the tables hold only
names and hashes, never GL.iNet's files.
"""
import hashlib, os, subprocess, sys

repo, roots, out = sys.argv[1:4]
only = sys.argv[4:]
os.makedirs(out, exist_ok=True)
# blob -> (commit, path) where the blob first appeared, one pass over history
first = {}
log = subprocess.Popen(["git", "-C", repo, "log", "--all", "--reverse", "--raw", "--no-abbrev",
                        "--no-renames", "--format=C %H"], stdout=subprocess.PIPE, text=True)
commit = None
for line in log.stdout:
    if line.startswith("C "):
        commit = line[2:].strip()
    elif line.startswith(":"):
        meta, path = line.rstrip("\n").split("\t", 1)
        blob = meta.split()[3]
        if blob != "0" * 40:
            first.setdefault(blob, (commit, path))
vkey = lambda v: [int(x) for x in v.split(".")]
for rel in sorted(only or os.listdir(roots), key=vkey):
    root = f"{roots}/{rel}"
    files = subprocess.run(["find", f"{root}/www/i18n", "-type", "f"], capture_output=True, text=True).stdout.split()
    rows, missing = [], []
    for f in sorted(files):
        data = open(f, "rb").read()
        blob = hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()
        p = f[len(root):]
        if blob in first:
            c, rp = first[blob]
            rows.append(f"| `{p}` | `{c}` | `{rp}` | `{hashlib.sha256(data).hexdigest()}` |")
        else:
            missing.append(f"- `{p}`")
    L = [f"# Translations of {rel} from gl-inet/router-sdk-languages", "",
         "Generated by `analysis/i18n-sources.py`. Each file is downloaded from",
         "https://github.com/gl-inet/router-sdk-languages at the commit shown and checked",
         f"against the SHA256 ({len(rows)} of {len(files)} files).", "",
         "| Image file | Commit | Path | SHA256 |", "|---|---|---|---|", *rows]
    if missing:
        L += ["", f"Not in the repository ({len(missing)}, copied from the image):", "", *missing]
    open(f"{out}/{rel}.md", "w").write("\n".join(L) + "\n")
    print(f"{rel}: {len(rows)} of {len(files)}", flush=True)
